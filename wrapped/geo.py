UNKNOWN_CITY = "未知地区"


def nearest_city(lat: float, lon: float, max_km: float = 150.0) -> tuple[str, float]:
    """返回 (城市名, 距离公里)。超过 max_km 判为未知地区。"""
    best_name, best_d = UNKNOWN_CITY, float("inf")
    for name, clat, clon in CITIES:
        d = haversine(lat, lon, clat, clon)
        if d < best_d:
            best_name, best_d = name, d
    if best_d > max_km:
        return UNKNOWN_CITY, best_d
    return best_name, best_d


def tz_offset_hours(lon: float, lat: float | None = None) -> int:
    """由经纬度粗推 UTC 偏移（整数小时）。

    这是**近似**：真实时区以国界划分。为了不把常识性错误写进报告，
    对中国大陆范围直接按东八区处理（新疆地理上偏西但官方时间仍是 +8）。
    其他地区按经度 15° 一格推算，跨境旅行够用。
    """
    if lat is not None and 73.0 <= lon <= 135.5 and 18.0 <= lat <= 53.6:
        return 8
    return max(-12, min(14, int(round(lon / 15.0))))
