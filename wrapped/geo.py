"""地理工具：球面距离、城市反查、由经度粗推时区。"""

from __future__ import annotations

import math

EARTH_R_KM = 6371.0088


def haversine(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """两点球面距离（公里）。"""
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi = p2 - p1
    dlmb = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlmb / 2) ** 2
    return 2 * EARTH_R_KM * math.asin(min(1.0, math.sqrt(a)))


def haversine_arr(lat0: float, lon0: float, lats, lons):
    """向量化版本：一个点 到 一组点 的距离数组（公里）。"""
    import numpy as np

    p0, l0 = math.radians(lat0), math.radians(lon0)
    p = np.radians(np.asarray(lats, dtype=float))
    l = np.radians(np.asarray(lons, dtype=float))
    a = np.sin((p - p0) / 2) ** 2 + math.cos(p0) * np.cos(p) * np.sin((l - l0) / 2) ** 2
    return 2 * EARTH_R_KM * np.arcsin(np.minimum(1.0, np.sqrt(a)))


